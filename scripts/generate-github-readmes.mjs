#!/usr/bin/env node

import { execFileSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { join, resolve } from "node:path";

const projectRoot = resolve(import.meta.dirname, "..");
const resourcesRoot = join(projectRoot, "Sources", "SlimLuma", "Resources");
const outputRoot = join(projectRoot, "docs", "readme");
const checksOnly = process.argv.includes("--check");
const releasesURL = "https://github.com/ChineseMao/SlimLuma/releases";

const locales = [
  ["zh-Hans", "简体中文"],
  ["zh-Hant", "繁體中文"],
  ["en", "English"],
  ["hi", "हिन्दी"],
  ["es-419", "Español (Latinoamérica)"],
  ["es-ES", "Español (España)"],
  ["ar", "العربية"],
  ["fr", "Français"],
  ["bn", "বাংলা"],
  ["pt-BR", "Português (Brasil)"],
  ["pt-PT", "Português (Portugal)"],
  ["id", "Bahasa Indonesia"],
  ["ur", "اردو"],
  ["ru", "Русский"],
  ["de", "Deutsch"],
  ["ja", "日本語"],
  ["sw", "Kiswahili"],
  ["pa-Arab", "پنجابی"],
  ["te", "తెలుగు"],
  ["pcm", "Naijá"],
];

function translations(locale) {
  const path = join(
    resourcesRoot,
    `${locale}.lproj`,
    "Localizable.strings",
  );
  const output = execFileSync(
    "/usr/bin/plutil",
    ["-convert", "json", "-o", "-", path],
    { encoding: "utf8" },
  );
  return JSON.parse(output);
}

function languageSelector(currentLocale) {
  return locales
    .map(([locale, name]) => {
      const label = locale === currentLocale ? `**${name}**` : name;
      return `[${label}](README.${locale}.md)`;
    })
    .join(" · ");
}

function document(locale) {
  const table = translations(locale);
  const t = (key) => {
    const value = table[key];
    if (typeof value !== "string" || value.length === 0) {
      throw new Error(`${locale} is missing README localization key: ${key}`);
    }
    return value;
  };

  return `<!-- Generated by scripts/generate-github-readmes.mjs. -->

# SlimLuma

${languageSelector(locale)}

> ${t("本地媒体瘦身工具")}

${t("支持常见图片、视频和 PDF，也可以拖入整个文件夹")}

## ${t("功能与原理")}

- **${t("图片")}** — ${t("先纠正方向，再按比例缩小、重编码和处理 profile；PNG、WebP 与 AVIF 的设置会映射为对应引擎参数。")}
- **${t("视频")}** — ${t("画面缩放保持比例、不放大并对齐偶数尺寸；音频转 AAC，MP4 字幕转 mov_text，MKV 字幕尽量复制，MP4 开启 faststart。")}
- **PDF** — ${t("qpdf 会重组对象流并重新压缩可压缩数据；Ghostscript 还能降低内嵌图片的像素密度、质量或色彩复杂度。文字型 PDF 通常收益较小，扫描件通常更明显。")}
- **${t("目标文件大小")}** — ${t("SlimLuma 会逐级调整质量；必要时缩小尺寸，以得到不超过目标的最清晰安全结果。目标大小需要 ImageMagick。")} ${t("H.264 与 HEVC 可按目标大小执行两遍软件编码，并为音频、字幕和容器预留空间；AV1 与单独音频压缩暂不支持目标体积。")}
- **${t("文件队列")}** — ${t("图片、视频和 PDF 可以混合加入；队列允许 1–6 个并发任务，开始时冻结整批设置。")}
- **${t("安全")}** — ${t("专业引擎只写入目标目录中的 .slimluma 隐藏临时文件，不直接碰原件。")}
- **${t("结果守门")}** — ${t("按图片、视频或 PDF 的完整性规则重新读取，发现关键退化就拒绝输出。")}
- **${t("自动化")}** — ${t("从剪贴板、监控文件夹和 Finder 直接进入压缩队列")}

## ${t("安装")}

1. [${t("从 GitHub Releases 下载适用于 macOS 的 Universal 版本。")}](${releasesURL})
2. ${t("将 SlimLuma.app 移到“应用程序”文件夹。")}
3. ${t("打开“引擎与设置”并选择“一键补齐推荐引擎”。")}

${t("SlimLuma 使用 Homebrew 安装 ImageMagick、FFmpeg、qpdf 与 Ghostscript；媒体文件始终留在这台 Mac。")}

## CLI

\`\`\`bash
slimluma compress photo.jpg movie.mov report.pdf
slimluma compress movie.mov --video-codec hevc --target-size-mb 25
slimluma engines
\`\`\`

## ${t("本地数据与隐私")}

${t("压缩过程不上传媒体文件。只有用户主动打开许可网站、brew.sh 或执行 Homebrew 安装时，浏览器或 Homebrew 才会访问网络。")}

[${t("有关架构、验证边界、许可证和发布说明，请查看主仓库文档。")}](../../README.md)
`;
}

mkdirSync(outputRoot, { recursive: true });
const mismatches = [];
for (const [locale] of locales) {
  const path = join(outputRoot, `README.${locale}.md`);
  const expected = document(locale);
  if (checksOnly) {
    if (!existsSync(path) || readFileSync(path, "utf8") !== expected) {
      mismatches.push(path);
    }
  } else {
    writeFileSync(path, expected);
  }
}

if (mismatches.length > 0) {
  throw new Error(
    `GitHub README translations are stale:\n${mismatches.join("\n")}`,
  );
}

console.log(
  `${checksOnly ? "Verified" : "Generated"} ${locales.length} GitHub README translations.`,
);
